// «a, b и c» / «a, b and c».
export function listJoin(lang, items) {
  const list = items.filter(Boolean);
  if (list.length <= 1) return list.join('');
  const and = lang === 'ru' ? ' и ' : ' and ';
  return `${list.slice(0, -1).join(', ')}${and}${list[list.length - 1]}`;
}
